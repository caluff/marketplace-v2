const ts = require("typescript");
const fs = require("node:fs");
const path = require("node:path");
const sources = ["contracts.ts", "claim-contracts.ts"].map((file) => path.resolve(__dirname, "../src/lib/order-tracking", file));
const target = path.resolve(__dirname, "../.mercur/order-tracking-contracts.d.ts");
const program = ts.createProgram(sources, {
  strict: true,
  skipLibCheck: true,
  target: ts.ScriptTarget.ES2021,
  module: ts.ModuleKind.Node16,
  moduleResolution: ts.ModuleResolutionKind.Node16,
});
const checker = program.getTypeChecker();
const declarations = sources.flatMap((source) => program.getSourceFile(source).statements.filter(ts.isTypeAliasDeclaration)).map((node) => {
  const type = checker.getTypeAtLocation(node);
  const rendered = checker.typeToString(type, node, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias);
  return `export type ${node.name.text} = ${rendered};`;
}).join("\n");
const result = '// Generated by scripts/generate-order-tracking-contracts.cjs. Do not edit.\nimport type { OrderStatus } from "@medusajs/framework/utils";\n\n' + declarations + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== result) {
    throw new Error("Order tracking contracts are stale; run pnpm tracking:contracts:generate");
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
