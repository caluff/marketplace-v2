const ts = require("typescript");
const fs = require("node:fs");
const path = require("node:path");
const source = path.resolve(__dirname, "../src/api/auth/google/complete/contracts.ts");
const vendorSource = path.resolve(__dirname, "../src/api/auth/vendor-session/contracts.ts");
const accountSource = path.resolve(__dirname, "../src/api/auth/account/email-verification/contracts.ts");
const oneTapSource = path.resolve(__dirname, "../src/lib/google-one-tap/contracts.ts");
const target = path.resolve(__dirname, "../.mercur/auth-contracts.d.ts");
const program = ts.createProgram([source, vendorSource, accountSource, oneTapSource], { strict: true, skipLibCheck: true, target: ts.ScriptTarget.ES2021, module: ts.ModuleKind.Node16, moduleResolution: ts.ModuleResolutionKind.Node16 });
const checker = program.getTypeChecker();
const file = program.getSourceFile(source);
const exported = checker.getExportsOfModule(checker.getSymbolAtLocation(file));
const input = exported.find(symbol => symbol.name === "CompleteGoogleAuthInput");
const inputType = checker.getDeclaredTypeOfSymbol(checker.getAliasedSymbol(input));
const printer = ts.createPrinter();
const declarations = [file, program.getSourceFile(vendorSource), program.getSourceFile(accountSource)].flatMap(sourceFile => sourceFile.statements.filter(ts.isTypeAliasDeclaration).map(node => printer.printNode(ts.EmitHint.Unspecified, node, sourceFile))).join("\n");
const accountFile = program.getSourceFile(accountSource);
const accountExports = checker.getExportsOfModule(checker.getSymbolAtLocation(accountFile));
const accountInputs = ["RequestAccountEmailVerificationInput", "ConfirmAccountEmailVerificationInput"].map(name => {
  const symbol = accountExports.find(entry => entry.name === name);
  return "export type " + name + " = " + checker.typeToString(checker.getDeclaredTypeOfSymbol(checker.getAliasedSymbol(symbol)), accountFile, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias) + ";";
}).join("\n");
const oneTapFile = program.getSourceFile(oneTapSource);
const oneTapDeclarations = oneTapFile.statements.filter(ts.isTypeAliasDeclaration).map(node =>
  `export type ${node.name.text} = ${checker.typeToString(checker.getTypeAtLocation(node), node, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias)};`
).join("\n");
const result = "// Generated by scripts/generate-auth-contracts.cjs. Do not edit.\n\nexport type CompleteGoogleAuthInput = " + checker.typeToString(inputType, file, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias) + ";\n" + declarations + "\n" + accountInputs + "\n" + oneTapDeclarations + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== result) throw new Error("Auth contracts are stale; run pnpm auth:contracts:generate");
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
