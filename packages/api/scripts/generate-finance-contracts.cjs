const ts = require("typescript");
const fs = require("node:fs");
const path = require("node:path");
const source = path.resolve(__dirname, "../src/lib/order-finance/contracts.ts");
const target = path.resolve(__dirname, "../.mercur/finance-contracts.d.ts");
const program = ts.createProgram([source], {
  strict: true, skipLibCheck: true, target: ts.ScriptTarget.ES2021,
  module: ts.ModuleKind.Node16, moduleResolution: ts.ModuleResolutionKind.Node16,
});
const checker = program.getTypeChecker();
const file = program.getSourceFile(source);
const printer = ts.createPrinter();
const declarations = file.statements.filter(ts.isTypeAliasDeclaration).map((node) => {
  if (node.name.text !== "OrderFinanceInput") return printer.printNode(ts.EmitHint.Unspecified, node, file);
  const type = checker.getTypeAtLocation(node);
  return `export type OrderFinanceInput = ${checker.typeToString(type, file, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias)};`;
}).join("\n");
const result = "// Generated by scripts/generate-finance-contracts.cjs. Do not edit.\n" + declarations + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== result) throw new Error("Finance contracts are stale; run pnpm finance:contracts:generate");
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
