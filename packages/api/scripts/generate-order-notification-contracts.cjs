const ts = require("typescript");
const fs = require("node:fs");
const path = require("node:path");
const source = path.resolve(
  __dirname,
  "../src/api/vendor/order-notifications/contracts.ts",
);
const target = path.resolve(
  __dirname,
  "../.mercur/order-notification-contracts.d.ts",
);
const program = ts.createProgram([source], {
  strict: true,
  skipLibCheck: false,
  target: ts.ScriptTarget.ES2021,
  module: ts.ModuleKind.Node16,
  moduleResolution: ts.ModuleResolutionKind.Node16,
});
const checker = program.getTypeChecker();
const file = program.getSourceFile(source);

const declarations = file.statements
  .filter(ts.isTypeAliasDeclaration)
  .map((node) => {
    const type = checker.getTypeAtLocation(node);
    const rendered = checker.typeToString(
      type,
      node,
      ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias,
    );
    return `export type ${node.name.text} = ${rendered};`;
  })
  .join("\n");
const result =
  "// Generated by scripts/generate-order-notification-contracts.cjs. Do not edit.\n" +
  declarations +
  "\n";
if (process.argv.includes("--check")) {
  if (
    !fs.existsSync(target) ||
    fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== result
  )
    throw new Error(
      "Order notification contracts are stale; run pnpm orders:contracts:generate",
    );
  const consumerProgram = ts.createProgram([target], {
    strict: true,
    skipLibCheck: false,
    noEmit: true,
    target: ts.ScriptTarget.ES2021,
    module: ts.ModuleKind.Node16,
    moduleResolution: ts.ModuleResolutionKind.Node16,
  });
  const diagnostics = ts.getPreEmitDiagnostics(consumerProgram);
  if (diagnostics.length > 0) {
    console.error(
      ts.formatDiagnosticsWithColorAndContext(diagnostics, {
        getCurrentDirectory: ts.sys.getCurrentDirectory,
        getCanonicalFileName: (fileName) => fileName,
        getNewLine: () => ts.sys.newLine,
      }),
    );
    throw new Error(
      "Order notification contract declaration failed typechecking",
    );
  }
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
