const ts = require("typescript");
const fs = require("node:fs");
const path = require("node:path");
const source = path.resolve(
  __dirname,
  "../src/api/store/products/search/contracts.ts",
);
const target = path.resolve(__dirname, "../.mercur/search-contracts.d.ts");
const program = ts.createProgram([source], {
  strict: true,
  skipLibCheck: true,
  target: ts.ScriptTarget.ES2021,
  module: ts.ModuleKind.Node16,
  moduleResolution: ts.ModuleResolutionKind.Node16,
});
const checker = program.getTypeChecker();
const file = program.getSourceFile(source);
const exportsList = checker.getExportsOfModule(
  checker.getSymbolAtLocation(file),
);
const input = exportsList.find(
  (symbol) => symbol.name === "StoreSearchProductsInput",
);
const inputType = checker.getDeclaredTypeOfSymbol(
  checker.getAliasedSymbol(input),
);
const printer = ts.createPrinter();
const declarations = file.statements
  .filter(ts.isTypeAliasDeclaration)
  .map((node) => printer.printNode(ts.EmitHint.Unspecified, node, file))
  .join("\n");
const result =
  '// Generated by scripts/generate-search-contracts.cjs. Do not edit.\nimport type { HttpTypes } from "@medusajs/framework/types";\n\n' +
  "export type StoreSearchProductsInput = " +
  checker.typeToString(
    inputType,
    file,
    ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias,
  ) +
  ";\n" +
  declarations +
  "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== result)
    throw new Error(
      "Search contracts are stale; run pnpm search:contracts:generate",
    );
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
