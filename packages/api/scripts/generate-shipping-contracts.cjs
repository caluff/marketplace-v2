const ts = require("typescript");
const fs = require("node:fs");
const path = require("node:path");
const sources = [
  "../src/api/vendor/shipping-configuration/validators.ts",
  "../src/lib/vendor-shipping/coverage.ts",
].map((file) => path.resolve(__dirname, file));
const target = path.resolve(__dirname, "../.mercur/shipping-contracts.d.ts");
const program = ts.createProgram(sources, {
  strict: true,
  skipLibCheck: true,
  target: ts.ScriptTarget.ES2021,
  module: ts.ModuleKind.Node16,
  moduleResolution: ts.ModuleResolutionKind.Node16,
});
const checker = program.getTypeChecker();
const declarations = sources
  .flatMap((source) =>
    program
      .getSourceFile(source)
      .statements.filter(ts.isTypeAliasDeclaration)
      .map(
        (node) =>
          `export type ${node.name.text} = ${checker.typeToString(checker.getTypeAtLocation(node), node, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.InTypeAlias)};`,
      ),
  )
  .join("\n");
const result =
  "// Generated by scripts/generate-shipping-contracts.cjs. Do not edit.\n" +
  declarations +
  "\n";
if (process.argv.includes("--check")) {
  if (
    !fs.existsSync(target) ||
    fs.readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== result
  )
    throw new Error(
      "Shipping contracts are stale; run pnpm shipping:contracts:generate",
    );
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, result);
}
